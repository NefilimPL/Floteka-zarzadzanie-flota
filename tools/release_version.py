"""Prepare one embedded version for tagged EXE and Excel builds."""

import argparse
from dataclasses import dataclass
from importlib.util import cache_from_source
import json
import os
from pathlib import Path
import re

from fleet.branding import DEFAULT_VERSION


@dataclass(frozen=True)
class ReleaseVersion:
    version: str
    windows_version: tuple[int, int, int, int]
    prerelease: bool
    source_ref: str
    tag: str = ''


def parse_tag(tag: str) -> ReleaseVersion:
    match = re.fullmatch(r'[vV]((?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*))(-dev)?', tag)
    if match is None:
        raise ValueError('Tag must be vA.B.C.D or VA.B.C.D, optionally ending in -dev.')
    numbers = tuple(int(value) for value in match[1].split('.'))
    if any(value > 65535 for value in numbers):
        raise ValueError('Each Windows version component must be between 0 and 65535.')
    dev = bool(match[2])
    return ReleaseVersion(match[1] + ('-dev' if dev else ''), numbers, dev,
                          'dev' if dev else 'refs/tags/' + tag, tag)


def prepare_version(root: Path, tag: str | None = None) -> ReleaseVersion:
    if tag:
        release = parse_tag(tag)
    else:
        numbers = tuple(int(value) for value in DEFAULT_VERSION.split('.'))
        release = ReleaseVersion(DEFAULT_VERSION, numbers + (0,) * (4 - len(numbers)), False, '')
    root = Path(root)
    build = root / 'build'
    build.mkdir(parents=True, exist_ok=True)
    module = root / 'fleet' / '_build_version.py'
    module.write_text(f'# Generated by tools.release_version; do not edit.\nVERSION = {release.version!r}\n', encoding='utf-8')
    # Rapid consecutive builds can have the same .py size and timestamp second.
    Path(cache_from_source(str(module))).unlink(missing_ok=True)
    resource = f'''VSVersionInfo(
  ffi=FixedFileInfo(filevers={release.windows_version!r}, prodvers={release.windows_version!r}, mask=0x3f,
                    flags={2 if release.prerelease else 0}, OS=0x40004, fileType=0x1, subtype=0x0, date=(0, 0)),
  kids=[StringFileInfo([StringTable('041504b0', [
    StringStruct('FileDescription', 'Floteka - kierowcy, tiry i przyczepy'),
    StringStruct('FileVersion', {release.version!r}),
    StringStruct('InternalName', 'Floteka'),
    StringStruct('OriginalFilename', 'Floteka.exe'),
    StringStruct('ProductName', 'Floteka'),
    StringStruct('ProductVersion', {release.version!r})
  ])]), VarFileInfo([VarStruct('Translation', [1045, 1200])])]
)
'''
    (build / 'windows-version.txt').write_text(resource, encoding='utf-8')
    (build / 'version.json').write_text(json.dumps(release.__dict__, indent=2) + '\n', encoding='utf-8')
    return release


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--tag', default=os.environ.get('FLOTEKA_BUILD_TAG') or None)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument('--github-output', type=Path)
    args = parser.parse_args()
    release = prepare_version(args.root, args.tag)
    if args.github_output:
        with args.github_output.open('a', encoding='utf-8') as output:
            output.write(f'version={release.version}\nprerelease={str(release.prerelease).lower()}\ntag={release.tag}\n')
    print(json.dumps(release.__dict__))


if __name__ == '__main__':
    main()
